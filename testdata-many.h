/***********************************************************************
 * testdata-many.h                                                      *
 *                                                                      *
 * A list of genus 2 curves with (comparatively) many rational points,  *
 * to serve as test data for ratpoints.  The counterpart of             *
 * testdata.h, whose curves are random.                                 *
 *                                                                      *
 * The two files exercise the two regimes that matter in practice and   *
 * that behave very differently: on a random curve about one numerator  *
 * in 10^4 survives the first phase of the sieve, on these curves up    *
 * to a hundred times more, so the best division of labour between the  *
 * two phases is quite different.  Anything tuned on one of them alone  *
 * -- in particular the constants that decide sp1 and sp2, see          *
 * ratpoints.h -- should be checked against the other.                  *
 *                                                                      *
 * The curves are taken from lists of genus 2 curves with many known    *
 * rational points and are ordered by increasing density, spanning the  *
 * whole range available: the expected fraction of numerators           *
 * surviving 11 sieving primes runs from 1.4e-05 to 8.5e-03.            *
 * The number of curves is chosen so that "make test1many" takes about  *
 * as long as "make test1".                                             *
 *                                                                      *
 * Michael Stoll, September 7, 2026                                     *
 ***********************************************************************/

